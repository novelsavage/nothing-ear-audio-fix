#!/usr/bin/env python3
"""Scoped backport of WirePlumber !794 for the exact tested vendor script.

https://github.com/PipeWire/wireplumber/commit/83d08dfa4370
No vendor source is distributed: generate from the installed version and retire
our override automatically when that source changes.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile

SOURCE = Path('/usr/share/wireplumber/scripts/monitors/bluez.lua')
SUPPORTED_HASHES = {'ed11c10760a5489eb6d036a66f0bc352ba5d2ffbe4df3f115ec2107a16c0ee7e'}
# Also recognizes the local workaround installed before repository integration.
MARKER = '-- Generated by nothing-ear-loopback-compat.py; do not edit.\n'


def validate_address(address):
    if not re.fullmatch(r'(?:[0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2}', address):
        raise ValueError('a Bluetooth address in AA:BB:CC:DD:EE:FF format is required')
    return address.upper()


def build_script(source, address):
    address = validate_address(address)
    creation = '  local sink_loopback = spa_device:get_managed_object (LOOPBACK_SINK_ID)\n'
    naming = '  properties["node.name"] = name:gsub("([^%w_%-%.])", "_")\n'
    if source.count(creation) != 1 or source.count(naming) != 1:
        raise ValueError('unexpected vendor script structure')
    guard = f'''  -- Upstream !794 removes sink loopbacks to fix KDE/GNOME volume control.
  -- Scope this backport to the selected device; keep its microphone loopback.
  if props["api.bluez5.address"] == "{address}" then
    return
  end

'''
    stable_name = f'''  -- Keep the existing default output name across A2DP/HFP profile changes.
  if dev_props["api.bluez5.address"] == "{address}" and
      (factory == "api.bluez5.a2dp.sink" or factory == "api.bluez5.sco.sink") then
    properties["node.name"] = "bluez_output.{address}"
  end
'''
    return MARKER + source.replace(creation, guard + creation).replace(naming, naming + stable_name)


def inspect(source_path, target_path, address):
    source = source_path.read_bytes() if source_path.exists() else b''
    supported = hashlib.sha256(source).hexdigest() in SUPPORTED_HASHES
    # A symlink is somebody else's override, even when its contents match ours.
    owned = (target_path.is_file() and not target_path.is_symlink()
             and target_path.read_text().startswith(MARKER))
    expected = build_script(source.decode(), address) if supported else None
    active = owned and target_path.read_text() == expected
    return {'vendor_supported': supported, 'owned': owned, 'current': active,
            'target': str(target_path), 'vendor_sha256': hashlib.sha256(source).hexdigest()}


def prepare(source_path, target_path, address):
    state = inspect(source_path, target_path, address)
    if (target_path.exists() or target_path.is_symlink()) and not state['owned']:
        raise ValueError(f'refusing to overwrite an unrelated override: {target_path}')
    if not state['vendor_supported']:
        if state['owned']:
            target_path.unlink()
            print('Retired local Bluetooth override: vendor script changed.')
        else:
            print('Vendor script is outside the tested version; no Bluetooth override applied.')
        return False
    if not state['current']:
        target_path.parent.mkdir(parents=True, exist_ok=True)
        result = build_script(source_path.read_text(), address)
        descriptor, temporary = tempfile.mkstemp(prefix='.bluez-', dir=target_path.parent)
        try:
            with os.fdopen(descriptor, 'w') as stream:
                stream.write(result)
            os.chmod(temporary, 0o644)
            os.replace(temporary, target_path)
        finally:
            Path(temporary).unlink(missing_ok=True)
    print('Bluetooth output loopback bypass enabled for the selected device; microphone unchanged.')
    return not state['current']


def main():
    data_root = Path(os.environ.get('XDG_DATA_HOME', Path.home() / '.local/share'))
    state_root = Path(os.environ.get('XDG_STATE_HOME', Path.home() / '.local/state'))
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--address', default=os.environ.get('NOTHING_EAR_ADDRESS'))
    parser.add_argument('--output', type=Path, default=data_root / 'wireplumber/scripts/monitors/bluez.lua')
    parser.add_argument('--check', action='store_true', help='print status as JSON without changing files')
    args = parser.parse_args()
    try:
        address = args.address or (state_root / 'nothing-ear-audio-fix/device-address').read_text().strip()
        address = validate_address(address)
        if args.check:
            print(json.dumps(inspect(SOURCE, args.output, address)))
        else:
            prepare(SOURCE, args.output, address)
    except (OSError, UnicodeError, ValueError) as error:
        print(f'Nothing Ear compatibility: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
